// Started by FrontendBrowserIntegrationTests against an isolated, disposable backend.
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'
import { chromium } from 'playwright'
import { createServer } from 'vite'
import { endpoints } from '../src/apiCatalog.ts'

assert.ok(process.env.LABFLOW_FRONTEND_TEST_EMAIL, 'Use the opt-in backend test harness')
assert.ok(process.env.LABFLOW_BACKEND_URL, 'An isolated test backend URL is required')
const output = resolve('test-results')
await mkdir(output, { recursive: true })
const server = await createServer({ server: { host: '127.0.0.1', port: 0, strictPort: false } })
let browser
let page
const observed = new Set()
const errors = []

try {
  await server.listen()
  const base = `http://127.0.0.1:${server.httpServer.address().port}`
  browser = await chromium.launch({ headless: true })
  page = await browser.newPage({ viewport: { width: 1440, height: 1080 } })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(base + '/#/api-test')
  await page.getByRole('heading', { name: '직접 연결하고, 확인하세요.' }).waitFor()

  async function go(id) {
    await page.evaluate(value => { window.location.hash = `/api-test/${value}` }, id)
    await page.waitForFunction(title => document.querySelector('.wb-form h2')?.textContent === title, endpoints.find(item => item.id === id).title)
  }
  async function send(id, expected, changes = {}) {
    await go(id)
    for (const [field, value] of Object.entries(changes)) await page.locator(`#field-${field}`).fill(value)
    const operation = endpoints.find(item => item.id === id)
    const promise = page.waitForResponse(response => {
      const url = new URL(response.url())
      const pattern = operation.path.replace(/\{[^}]+\}/g, '[^/]+')
      return new RegExp(`^${pattern}$`).test(url.pathname) && response.request().method() === operation.method
    })
    await page.locator('.wb-primary').click()
    const response = await promise
    assert.equal(response.status(), expected ?? operation.status, `${id} HTTP result`)
    await page.waitForFunction(() => document.querySelector('.wb-primary')?.disabled === false)
    if (response.status() === operation.status) observed.add(id)
    return response
  }

  await send('csrf')
  await send('signup', 201, { name: 'Frontend browser tester', email: process.env.LABFLOW_FRONTEND_TEST_EMAIL, password: 'browser-test-password-123', confirmPassword: 'browser-test-password-123' })
  // A later login resumes verification, without issuing an authenticated session.
  const pendingLogin = await browser.newPage()
  await pendingLogin.goto(base + '/#/login')
  await pendingLogin.getByLabel('이메일', { exact: true }).fill(process.env.LABFLOW_FRONTEND_TEST_EMAIL)
  await pendingLogin.getByLabel('비밀번호', { exact: true }).fill('incorrect-password')
  await pendingLogin.locator('button[type="submit"]').click()
  await pendingLogin.getByText('로그인이 필요합니다. 다시 로그인해 주세요.', { exact: true }).waitFor()
  assert.equal(new URL(pendingLogin.url()).hash, '#/login')
  await pendingLogin.getByLabel('비밀번호', { exact: true }).fill('browser-test-password-123')
  await pendingLogin.locator('button[type="submit"]').click()
  await pendingLogin.waitForURL('**/#/verify')
  assert.equal(await pendingLogin.getByLabel('이메일', { exact: true }).inputValue(), process.env.LABFLOW_FRONTEND_TEST_EMAIL)
  await pendingLogin.getByLabel('인증 코드', { exact: true }).waitFor()
  assert.equal((await pendingLogin.context().cookies()).some(cookie => ['access_token', 'refresh_token'].includes(cookie.name)), false)
  await pendingLogin.getByRole('link', { name: '로그인으로 돌아가기' }).click()
  assert.equal(await pendingLogin.getByLabel('비밀번호', { exact: true }).inputValue(), '')
  await pendingLogin.context().close()
  await send('resend') // Acknowledgement during the cooldown is still 202.
  await send('verify', 204, { code: 'ABC234' })
  await send('login') // The email and password should carry over from sign-up.
  assert.ok((await page.context().cookies()).some(cookie => cookie.name === 'access_token' && cookie.httpOnly))
  assert.equal(await page.evaluate(() => document.cookie.includes('access_token=')), false)
  await send('project-create', 201, { name: 'Browser integration project' })
  const projectId = await page.getByLabel('Project ID', { exact: true }).inputValue()
  assert.match(projectId, /^\d+$/)
  await send('project-get') // Would be 404 if a Java long were rounded.
  assert.equal(await page.getByLabel('Project version', { exact: true }).inputValue(), '0')
  await page.getByLabel('사용자 API를 쿠키 없이 호출', { exact: true }).check()
  await send('project-get', 401) // PRIVATE, anonymous.
  await page.getByLabel('사용자 API를 쿠키 없이 호출', { exact: true }).uncheck()
  await send('project-list')
  await page.locator('.wb-project-results button').first().click()
  assert.equal(await page.getByLabel('Project ID', { exact: true }).inputValue(), projectId)
  await send('project-update', 204, { name: 'Updated browser project' })
  await send('project-get')
  assert.notEqual(await page.getByLabel('Project version', { exact: true }).inputValue(), '0')
  await go('project-update')
  await page.locator('#field-visibility').selectOption('PUBLIC')
  await send('project-update')
  await page.getByLabel('사용자 API를 쿠키 없이 호출', { exact: true }).check()
  await send('project-get', 200) // PUBLIC, anonymous.
  await page.getByLabel('사용자 API를 쿠키 없이 호출', { exact: true }).uncheck()
  await page.getByLabel('CSRF 자동 적용', { exact: true }).uncheck()
  await send('project-create', 403)
  await page.getByLabel('CSRF 자동 적용', { exact: true }).check()
  await send('key-issue')
  const key = await page.getByLabel('SDK API key', { exact: true }).inputValue()
  assert.ok(key.startsWith('lfp_'))
  assert.equal(await page.locator('.wb-response-code').innerText().then(value => value.includes(key)), false)
  await send('run-create')
  const completedRun = await page.getByLabel('Run ID', { exact: true }).inputValue()
  await send('run-params')
  await send('run-params', 409, { parameters: '{"optimizer":"sgd"}' })
  await send('run-metrics')
  await send('run-metrics', 400, { metrics: '{"loss":"0.5"}' })
  await page.getByLabel('JSON 직접 편집', { exact: true }).check()
  await page.locator('#raw-body').fill('{"metrics":{"loss":"invalid"}}')
  await send('run-metrics', 400)
  await send('run-logs')
  await send('run-texts')
  await send('run-system')
  await send('run-complete')
  await send('run-complete') // Idempotent completion.
  await send('run-get')
  assert.match(await page.locator('.wb-response-code').innerText(), /COMPLETED/)
  await send('run-logs', 409) // A terminal run rejects further records.
  await page.getByLabel('SDK API key', { exact: true }).fill('lfp_invalid-key')
  await send('run-get', 401)
  await page.getByLabel('SDK API key', { exact: true }).fill(key)
  await page.getByLabel('Run ID', { exact: true }).fill('1')
  await send('run-get', 404)
  await page.getByLabel('Run ID', { exact: true }).fill(completedRun)
  await send('run-create', 201, { name: 'Browser failed run' })
  const failedRun = await page.getByLabel('Run ID', { exact: true }).inputValue()
  await send('run-fail')
  await send('run-fail') // Same failure is idempotent.
  await send('run-get')
  assert.match(await page.locator('.wb-response-code').innerText(), /FAILED/)
  await send('web-run-list')
  await send('web-run-get')
  await send('web-run-records')
  await send('refresh')

  // Use a second project for cross-project denial and the destructive endpoint.
  await send('project-create', 201, { name: 'Disposable browser project' })
  await send('project-get')
  await send('key-issue')
  await send('run-get', 403) // This key cannot access the first project's run.
  page.once('dialog', dialog => dialog.accept())
  await send('project-delete')
  await page.getByLabel('Project ID', { exact: true }).fill(projectId)
  await send('project-get')
  await page.getByLabel('SDK API key', { exact: true }).fill(key)
  await page.getByLabel('Run ID', { exact: true }).fill(failedRun)
  await send('logout')
  await send('project-list', 401)
  await send('run-get') // SDK authentication remains independent of the logged-out browser.
  assert.equal(observed.size, endpoints.length)
  assert.match(await page.locator('.wb-progress > strong').innerText(), /25\s*\/\s*25/)
  assert.deepEqual(errors, [])
  assert.equal(await page.evaluate(() => Object.keys(localStorage).length), 0)
  assert.equal(await page.evaluate(() => Object.keys(sessionStorage).length), 0)
  await go('run-metrics')
  await page.locator('#field-metrics').fill('{\n  "loss": 0.25,\n  "accuracy": 0.9\n}')
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0) })
  await page.screenshot({ path: resolve(output, 'api-workbench-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => window.scrollTo(0, 0))
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  await page.screenshot({ path: resolve(output, 'api-workbench-mobile.png'), fullPage: true })
  await page.goto(`${base}/#/projects`)
  await page.getByRole('heading', { name: '다시 만나 반가워요', exact: true }).waitFor()
  await page.getByRole('link', { name: 'API 테스트 도구 ↗', exact: true }).click()
  await page.getByRole('heading', { name: '직접 연결하고, 확인하세요.' }).waitFor()
  // Continue in the ordinary application using the same real backend data.
  await page.setViewportSize({ width: 1440, height: 1080 })
  await page.goto(`${base}/#/login`)
  await page.getByRole('heading', { name: '다시 만나 반가워요' }).waitFor()
  await page.screenshot({ path: resolve(output, 'application-login.png'), fullPage: true })
  await page.getByLabel('이메일', { exact: true }).fill(process.env.LABFLOW_FRONTEND_TEST_EMAIL)
  await page.getByLabel('비밀번호', { exact: true }).fill('browser-test-password-123')
  await page.getByRole('button', { name: /로그인/ }).click()
  await page.getByRole('heading', { name: 'Projects', exact: true }).waitFor()
  await page.getByRole('link').filter({ hasText: 'Updated browser project' }).first().waitFor()
  await page.screenshot({ path: resolve(output, 'application-projects.png'), fullPage: true })
  await page.getByRole('button', { name: '+ 새 프로젝트', exact: true }).click()
  await page.getByRole('dialog').getByLabel('프로젝트 이름', { exact: true }).fill('웹에서 만든 프로젝트')
  await page.getByRole('dialog').getByLabel('설명', { exact: true }).fill('실제 CRUD 테스트')
  await page.getByRole('dialog').getByRole('button', { name: '프로젝트 만들기', exact: true }).click()
  await page.getByRole('heading', { name: '웹에서 만든 프로젝트', exact: true }).waitFor()
  await page.getByRole('heading', { name: '아직 실행한 실험이 없어요' }).waitFor()
  await page.getByRole('button', { name: '프로젝트 설정', exact: true }).click()
  await page.getByRole('dialog').getByLabel('프로젝트 이름', { exact: true }).fill('웹 프로젝트 수정')
  await page.getByRole('dialog').getByRole('button', { name: '변경사항 저장', exact: true }).click()
  await page.getByRole('heading', { name: '웹 프로젝트 수정', exact: true }).waitFor()
  await page.locator('.p-danger-zone summary').click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '프로젝트와 기록 삭제', exact: true }).click()
  await page.getByRole('heading', { name: 'Projects', exact: true }).waitFor()
  await page.getByRole('link').filter({ hasText: 'Updated browser project' }).first().click()
  await page.getByRole('heading', { name: 'Updated browser project', exact: true }).waitFor()
  await page.waitForFunction(() => document.querySelector('.p-stats strong')?.textContent === '2')
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0) })
  await page.screenshot({ path: resolve(output, 'application-overview.png'), fullPage: true })
  await page.getByRole('link', { name: 'API Keys', exact: true }).click()
  await page.getByLabel('키 이름', { exact: true }).fill('product-browser-key')
  await page.getByRole('button', { name: 'API key 발급', exact: true }).click()
  await page.getByLabel('발급된 API key', { exact: true }).waitFor()
  assert.ok((await page.getByLabel('발급된 API key', { exact: true }).inputValue()).startsWith('lfp_'))
  assert.equal(await page.evaluate(() => Object.keys(localStorage).length), 0)
  await page.getByRole('link', { name: 'Runs', exact: true }).click()
  await page.getByRole('link', { name: /browser-training/ }).first().click()
  await page.locator('[data-metric="loss"]').waitFor()
  await page.locator('[data-metric="accuracy"]').waitFor()
  await page.getByLabel('Metrics X-axis', { exact: true }).selectOption('epoch')
  await page.screenshot({ path: resolve(output, 'application-metrics.png'), fullPage: true })
  await page.getByRole('link', { name: 'Parameters', exact: true }).click()
  await page.getByText('batch_size', { exact: true }).waitFor()
  await page.getByRole('link', { name: 'Logs', exact: true }).click()
  await page.getByText('학습을 시작했습니다.', { exact: true }).waitFor()
  await page.getByLabel('로그 검색', { exact: true }).fill('없는 로그')
  assert.equal(await page.locator('.p-real-logs > div').count(), 0)
  await page.getByRole('link', { name: 'Texts', exact: true }).click()
  await page.getByText('고양이가 창가에 앉아 있다. 🐈', { exact: true }).waitFor()
  await page.getByRole('link', { name: 'System', exact: true }).click()
  await page.getByText('25%', { exact: true }).waitFor()
  await page.getByRole('link', { name: 'Metrics', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0) })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: resolve(output, 'application-mobile.png'), fullPage: true })
  // A separate anonymous browser can read PUBLIC results and cannot issue a key.
  const anonymousContext = await browser.newContext()
  const publicPage = await anonymousContext.newPage()
  await publicPage.goto(`${base}/#/projects/${projectId}/runs/${completedRun}/metrics`)
  await publicPage.locator('[data-metric="loss"]').waitFor()
  await anonymousContext.close()
  await page.getByRole('button', { name: '로그아웃', exact: true }).click()
  await page.getByRole('heading', { name: '다시 만나 반가워요' }).waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS: real application login, project CRUD, SDK key, real run charts, parameters/logs/text/system, public access, logout, mobile')
  console.log('PASS: all 25 API operations through real browser forms; HTTP 400/401/403/404/409; cookie/CSRF isolation; desktop/mobile')
} catch (error) {
  if (page) await page.screenshot({ path: resolve(output, 'api-workbench-failure.png'), fullPage: true }).catch(() => {})
  throw error
} finally {
  await browser?.close()
  await server.close()
}
