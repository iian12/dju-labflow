import assert from 'node:assert/strict';
import test from 'node:test';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { chromium } from 'playwright';
const baseURL = process.env.LABFLOW_BASE_URL ?? 'http://127.0.0.1:5181';
test('review', async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.setDefaultTimeout(8000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const open = async (path: string) => { await page.goto(`${baseURL}/#/` + path); };
  try {
    await open('projects/vision/runs');
    await page.getByRole('button', { name: /실패 2/ }).click();
    await page.getByLabel('Run 검색').fill('sweep');
    await page.getByLabel('표시 지표').selectOption('loss');
    await page.locator('.run-link').first().click();
    await page.getByRole('button', { name: '오류 로그 보기' }).click();
    await page.locator('.console .ERROR').waitFor();
    assert.equal(await page.locator('.console .INFO').count(), 0);
    await page.getByRole('link', { name: '← 실험 기록으로' }).click();
    assert.match(await page.locator('.filters .selected').innerText(), /실패/);
    assert.equal(await page.getByLabel('Run 검색').inputValue(), 'sweep');
    assert.equal(await page.getByLabel('표시 지표').inputValue(), 'loss');
    await page.reload();
    assert.equal(await page.getByLabel('Run 검색').inputValue(), 'sweep');
    await page.getByLabel('Run 검색').fill('');
    await page.getByRole('button', { name: /전체 18/ }).click();
    const checks = page.locator('table input[type=checkbox]');
    await checks.nth(0).check();
    await checks.nth(2).check();
    await page.getByRole('button', { name: '결과 비교' }).click();
    assert.equal(await page.getByLabel('비교 지표').inputValue(), 'loss');
    assert.match(await page.locator('.section-title p').first().innerText(), /val_loss/);
    await page.getByLabel('기준 Run').selectOption('vision-run-1040');
    await page.getByLabel('비교 지표').selectOption('accuracy');
    assert.match(await page.locator('.section-title p').first().innerText(), /val_accuracy/);
    await page.getByRole('checkbox', { name: '다른 설정만 보기' }).check();
    await page.screenshot({ path: join(tmpdir(), 'labflow-improved-compare.png'), fullPage: true });
    await page.getByRole('navigation',{name:'프로젝트 바로가기'}).getByRole('link',{name:/^Document retrieval$/}).click(); await page.getByRole('navigation',{name:'프로젝트 화면'}).waitFor();
    await page.locator('.project-tabs a[href$="/runs"]').click();
    assert.equal(await page.locator('.run-link').first().innerText(), 'bge-hard-negatives-01');
    await page.locator('.run-link').first().click();
    assert.match(await page.locator('.run-heading').innerText(), /BGE-small/);
    await page.getByRole('link', { name: 'Environment', exact: true }).click();
    assert.match(await page.locator('.keyvalues').innerText(), /A100/);
    await page.locator('.project-tabs a[href$="/settings"]').click();
    await page.getByRole('button', { name: '데모 키 생성', exact: true }).click();
    assert.equal(await page.locator('.key-reveal').count(), 1);
    await page.getByRole('navigation',{name:'프로젝트 바로가기'}).getByRole('link',{name:/^Image classification$/}).click();
    await page.locator('.project-tabs a[href$="/settings"]').click();
    assert.equal(await page.locator('.key-reveal').count(), 0);
    await page.getByRole('navigation',{name:'프로젝트 바로가기'}).getByRole('link',{name:/^Document retrieval$/}).click(); await page.getByRole('navigation',{name:'프로젝트 화면'}).waitFor();
    await page.locator('.project-tabs a[href$="/settings"]').click();
    assert.equal(await page.locator('.key-reveal').count(), 0);
    await page.getByRole('button', { name: '폐기', exact: true }).waitFor(); assert.equal(await page.getByRole('button', { name: '폐기', exact: true }).count(), 1);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: join(tmpdir(), 'labflow-improved-mobile.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log('PASS: project fixtures, list return and reload, scroll list, comparison metrics and baseline, key scoping, mobile layout. No page errors.');
  } finally {
    await browser.close();
  }
});
