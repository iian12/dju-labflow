import assert from 'node:assert/strict';
import test from 'node:test';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { chromium } from 'playwright';
const baseURL = process.env.LABFLOW_BASE_URL ?? 'http://127.0.0.1:5181';
test('navigation', async () => {
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 page.setDefaultTimeout(8000);
 const errors: string[] = [];page.on('pageerror',e=>errors.push(e.message));
 const projectLink=(name: string)=>page.getByRole('navigation',{name:'프로젝트 바로가기'}).getByRole('link',{name,exact:true});
 try{
 await page.goto(`${baseURL}/#/projects`);
 await page.locator('.project-card').first().click();
 await page.waitForURL('**/#/projects/vision/runs'); await page.getByRole('heading',{name:'Image classification',exact:true}).waitFor();
 const first=page.locator('.run-link').first();
 await first.waitFor();
 const box=await first.boundingBox();
 assert.ok(box);
 assert.ok(box.y>0&&box.y+box.height<900,'First Run visible without scroll');
 assert.equal(await page.evaluate(()=>scrollY),0);
 assert.equal(await page.locator('.overview-learning-curve').count(),0);
 await page.getByRole('button',{name:/실패 2/}).click();
 await page.getByLabel('Run 검색').fill('sweep');
 await page.getByLabel('표시 지표').selectOption('loss');
 await page.locator('table input[type=checkbox]').first().check();
 await projectLink('Document retrieval').click();
 await page.waitForURL('**/#/projects/language/overview');
 await page.getByRole('navigation',{name:'프로젝트 화면'}).getByRole('link',{name:/실험 기록/}).click();
 await page.waitForURL('**/#/projects/language/runs'); await page.getByRole('heading',{name:'Document retrieval',exact:true}).waitFor();
 assert.match(await page.locator('.run-link').first().innerText(),/bge/);
 await projectLink('Image classification').click();
 await page.waitForURL('**/#/projects/vision/overview');
 await page.getByRole('navigation',{name:'프로젝트 화면'}).getByRole('link',{name:/실험 기록/}).click();
 await page.waitForURL('**/#/projects/vision/runs'); await page.getByRole('heading',{name:'Image classification',exact:true}).waitFor();
 assert.equal(await page.getByLabel('Run 검색').inputValue(),'sweep');
 assert.equal(await page.getByLabel('표시 지표').inputValue(),'loss');
 assert.match(await page.locator('.filters .selected').innerText(),/실패/);
 assert.equal(await page.locator('table input:checked').count(),1);
 await page.locator('.run-link').first().click();
 await projectLink('Document retrieval').click();
 await page.waitForURL('**/#/projects/language/overview');
 await page.getByRole('navigation',{name:'프로젝트 화면'}).getByRole('link',{name:/실험 기록/}).click();
 await page.waitForURL('**/#/projects/language/runs'); await page.getByRole('heading',{name:'Document retrieval',exact:true}).waitFor();
 await page.getByRole('navigation',{name:'프로젝트 화면'}).getByRole('link',{name:'개요',exact:true}).click();
 await projectLink('Image classification').click();
 await page.waitForURL('**/#/projects/vision/overview');
 await page.getByLabel('대표 학습 곡선 표시 지표').selectOption('accuracy');
 await page.locator('.overview-learning-curve svg[aria-label="val_accuracy 학습 곡선"]').waitFor();
 await page.getByRole('navigation',{name:'프로젝트 화면'}).getByRole('link',{name:/실험 기록/}).click();
 await page.getByLabel('Run 검색').fill('');
 await page.getByRole('button',{name:/전체 18/}).click();
 await page.getByRole('button',{name:'선택 해제',exact:true}).click();
 const checks=page.locator('table input[type=checkbox]');
 await checks.nth(0).check();await checks.nth(1).check();
 await page.getByRole('button',{name:'결과 비교'}).click();
 await page.getByRole('heading',{name:'성능과 설정의 차이'}).waitFor();
 await page.getByRole('navigation',{name:'프로젝트 화면'}).getByRole('link',{name:/실험 기록/}).click();
 await page.screenshot({path:join(tmpdir(), 'labflow-navigation-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await projectLink('Document retrieval').click();
 await page.waitForURL('**/#/projects/language/overview');
 await page.getByRole('navigation',{name:'프로젝트 화면'}).getByRole('link',{name:/실험 기록/}).click();
 await page.waitForURL('**/#/projects/language/runs'); await page.getByRole('heading',{name:'Document retrieval',exact:true}).waitFor();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:join(tmpdir(), 'labflow-navigation-mobile.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS: visible first Run, sidebar overview navigation, per-project filters and selection, project switch from details, overview and compare, mobile.');
 }finally{await browser.close()}
});
